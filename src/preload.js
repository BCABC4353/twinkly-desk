const { contextBridge, ipcRenderer } = require('electron');

const call = (channel) => (payload) => ipcRenderer.invoke(channel, payload);

contextBridge.exposeInMainWorld('api', {
  discover: call('devices:discover'),
  addDevice: call('devices:add'),
  removeDevice: call('devices:remove'),
  refreshDevice: call('devices:refresh'),
  getScene: call('scene:get'),
  setPlace: call('scene:place'),
  setUnits: call('scene:units'),
  pushLayout: call('scene:layout'),
  status: call('ctl:status'),
  setMode: call('ctl:mode'),
  setBrightness: call('ctl:brightness'),
  setColor: call('ctl:color'),
  setEffect: call('ctl:effect'),
  liveStart: call('live:start'),
  liveStop: call('live:stop'),
  identify: call('live:identify'),
  saveMovie: call('movie:save'),
  mediaPlay: call('media:play'),
  mediaSave: call('media:save'),
  mediaPreset: call('media:preset'),
  deleteMovies: call('movies:delete'),
  libraryList: call('library:list'),
  libraryPlay: call('library:play'),
  playlistGet: call('playlist:get'),
  playlistPlay: call('playlist:play'),
  playlistStop: call('playlist:stop'),
  listPresets: call('presets:list'),
  savePreset: call('presets:save'),
  deletePreset: call('presets:delete'),
  applyPreset: call('presets:apply'),
  getSchedule: call('schedule:get'),
  setSchedule: call('schedule:set'),
  getSettings: call('settings:get'),
  setSettings: call('settings:set'),
  getLog: call('app:log'),
  liveStats: call('live:stats'),
  onFrame: (fn) => { ipcRenderer.on('frame', (_e, data) => fn(data)); },
  onChanged: (fn) => { ipcRenderer.on('changed', (_e, what) => fn(what)); },
});
