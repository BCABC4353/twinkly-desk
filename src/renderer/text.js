function textBitmap(message) {
  const glyphs = [];
  for (const raw of message) {
    const ch = raw.toUpperCase();
    glyphs.push(FONT[ch] || FONT['?']);
  }
  const width = glyphs.length * 6;
  const rows = Array.from({ length: 7 }, () => new Uint8Array(width));
  glyphs.forEach((g, gi) => {
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y][x] === '#') rows[y][gi * 6 + x] = 1;
  });
  return { rows, width, height: 7 };
}

function textSettings() {
  return {
    message: $('#tMsg').value,
    color: $('#tColor').value,
    bg: $('#tBg').value,
    sx: +$('#tWidth').value,
    sy: +$('#tHeight').value,
    speed: +$('#tSpeed').value,
    dir: $('#tDir').value,
  };
}

function buildTextSamples() {
  const st = textSettings();
  if (!st.message.trim()) return null;
  const aspect = sceneAspect();
  const rw = Math.max(4, aspect >= 1 ? 64 : Math.round(64 * aspect));
  const rh = Math.max(4, aspect >= 1 ? Math.round(64 / aspect) : 64);
  const bmp = textBitmap(st.message);
  const gw = Math.round(bmp.width * st.sx);
  const gh = Math.round(bmp.height * st.sy);
  const sprite = document.createElement('canvas');
  sprite.width = gw; sprite.height = gh;
  const sg = sprite.getContext('2d');
  sg.fillStyle = st.color;
  for (let y = 0; y < 7; y++) for (let x = 0; x < bmp.width; x++) if (bmp.rows[y][x]) sg.fillRect(Math.round(x * st.sx), Math.round(y * st.sy), Math.ceil(st.sx), Math.ceil(st.sy));
  const fps = deviceFps();
  const pxPerFrame = Math.max(0.25, st.speed * (rw / 64) / fps);
  const travel = rw + gw;
  const n = Math.max(1, Math.round(travel / pxPerFrame));
  const y0 = Math.round((rh - gh) / 2);
  const samples = [];
  for (let k = 0; k < n; k++) {
    const c = document.createElement('canvas');
    c.width = rw; c.height = rh;
    const g = c.getContext('2d');
    g.fillStyle = st.bg; g.fillRect(0, 0, rw, rh);
    g.imageSmoothingEnabled = false;
    const off = k * pxPerFrame;
    const x = st.dir === 'left' ? Math.round(rw - off) : Math.round(off - gw);
    g.drawImage(sprite, x, y0);
    samples.push({ img: c, dt: 1 / fps });
  }
  return samples;
}

function showText() {
  if (!S.scene.devices.length) return status('Add a set first');
  const samples = buildTextSamples();
  if (!samples) return status('Type a message first');
  M.kind = 'text';
  M.name = 'Text: ' + textSettings().message.trim().slice(0, 24);
  M.samples = samples;
  M.file = null;
  $('#mMaxSec').value = Math.max(+$('#mMaxSec').value, Math.ceil(samples.length / deviceFps()));
  buildClip();
}

$('#tShow').onclick = showText;
['tMsg', 'tColor', 'tBg', 'tWidth', 'tHeight', 'tSpeed', 'tDir'].forEach((id) => {
  const el = $('#' + id);
  el.addEventListener(el.type === 'range' ? 'input' : 'change', () => {
    const v = $('#' + id + 'Val'); if (v) v.textContent = el.value;
    if (M.kind === 'text') { clearTimeout(window.__textT); window.__textT = setTimeout(showText, 200); }
  });
});
